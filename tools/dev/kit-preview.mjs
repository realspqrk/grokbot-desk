  await page.click('#copy-amount .rs-copy__btn');
  st = await ev(() => { const c = document.getElementById('copy-amount'); return { state: c.dataset.state, value: c.querySelector('.rs-copy__value').textContent, last: window.KIT.copies.at(-1), toast: [...document.querySelectorAll('.rs-toast')].map((x) => x.textContent) }; });
