  await page.focus('#copy-code .rs-copy__btn');
  await ev(() => { window.__c = undefined; document.getElementById('kit-confirm').open({ word: 'DELETE' }).then((v) => { window.__c = v; }); });
  st = await ev(() => { const d = document.querySelector('#kit-confirm dialog'); return { open: d.open, modal: d.matches(':modal'), label: d.querySelector('label').textContent, focus: document.activeElement.className, disabled: d.querySelector('button[type=submit]').disabled }; });
