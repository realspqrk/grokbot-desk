  await page.click('#row-1 button[value="spaeter"]');
  st = await ev(() => window.__changes);
  check('choice: change events (no duplicate on re-click)', JSON.stringify(st) === '["spaeter","erledigt","ignorieren","spaeter"]', st);
  st = await ev(() => document.getElementById('row-2').value);
  check('choice: value attribute preselects (template restore)', st === 'spaeter', st);
  st = await ev(() => { const b = document.querySelector('#row-1 button[aria-checked="true"]'); const s = getComputedStyle(b); return { bg: s.backgroundColor, accent: getComputedStyle(document.documentElement).getPropertyValue('--rs-accent') }; });
