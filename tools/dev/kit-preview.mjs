await browser.close();

if (checks) {
  let fail = 0;
  for (const c of checks) {
    if (!c.ok) fail++;
    console.log((c.ok ? 'PASS ' : 'FAIL ') + c.name + (c.ok ? '' : '  ' + JSON.stringify(c.info)));
  }
  console.log(`\n${checks.length - fail}/${checks.length} checks passed`);
  console.log('screenshots: ' + outDir);
  process.exit(fail ? 1 : 0);
}
