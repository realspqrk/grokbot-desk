  check('copy: every copy icon is its own tab stop', JSON.stringify(st) === '[0,0,0]', st);
  st = await ev(() => { const c = document.getElementById('copy-draft'); return { tab: c.querySelector('.rs-copy__value').tabIndex, clamp: c.querySelector('.rs-copy__value').classList.contains('rs-copy__value--clamp'), more: !c.querySelector('.rs-copy__more').hidden }; });
