  st = await ev(() => { const b = document.querySelector('#copy-code .rs-copy__btn'); const r = b.getBoundingClientRect(); return { w: r.width, h: r.height, label: b.getAttribute('aria-label'), opacity: getComputedStyle(b).opacity }; });
  check('copy: icon-only <= 32 px with aria-label', st.w <= 32 && st.h <= 32 && st.label === 'Copy code', st);
  await page.mouse.move(1495, 5);
  st = await ev(() => getComputedStyle(document.querySelector('#copy-code .rs-copy__btn')).opacity);
  check('copy: visible at rest (copy-first)', st === '1', st);
